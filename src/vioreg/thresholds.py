"""Write configs/thresholds.yaml (format v2) from a baseline.json plus margins (session S4).

    python scripts/make_thresholds.py --baseline docs/variance/baseline.json \
        --rpe-ratio-max R --ate-geomean-ratio-max A [--coverage-drop-max 0.01] \
        [--trajectories results/variance/A_serial]

Per sequence the baseline entry is keyed by (vio_commit, image_digest, config_hash) and holds:
  ate_rmse, rpe_rmse  median over the baseline runs
  coverage, n         the WORST (minimum) over the baseline runs
  trajectory          baselines/<seq>.tum, the representative run, if --trajectories given
skip_s and align are carried over from the existing thresholds file.

Refuses (ThresholdsError) to write a baseline with a failed run or missing provenance, or
margins that the baseline itself would fail (ratio margins must be > 1).
"""
from __future__ import annotations

import shutil
from datetime import date
from pathlib import Path

import numpy as np
import yaml

KEY_FIELDS = ("vio_commit", "image_digest", "config_hash")


class ThresholdsError(RuntimeError):
    pass


def _check_margins(m: dict) -> dict:
    def num(k):
        v = m.get(k)
        if not isinstance(v, (int, float)) or isinstance(v, bool):
            raise ThresholdsError(f"margin {k} missing or not a number")
        return float(v)
    out = {"rpe_ratio_max": num("rpe_ratio_max"),
           "ate_geomean_ratio_max": num("ate_geomean_ratio_max"),
           "coverage_drop_max": num("coverage_drop_max")}
    if out["rpe_ratio_max"] <= 1.0 or out["ate_geomean_ratio_max"] <= 1.0:
        raise ThresholdsError("ratio margins must be > 1, or the baseline itself fails")
    if out["coverage_drop_max"] < 0:
        raise ThresholdsError("coverage_drop_max must be >= 0")
    return out


def _representative_index(per_run_ate) -> int:
    order = sorted(range(len(per_run_ate)), key=lambda i: per_run_ate[i])
    return order[len(order) // 2]  # same rule as score.py (upper median)


def build(baseline: dict, margins: dict, old_thresholds: dict,
          trajectories: Path | None = None, out_root: Path | None = None) -> dict:
    m = _check_margins(margins)
    old_seqs = old_thresholds.get("sequences", {})
    align = (old_thresholds.get("defaults") or {}).get("align", "posyaw")
    seqs = {}
    for seq, b in sorted(baseline["sequences"].items()):
        missing = [k for k in KEY_FIELDS if not b.get(k)]
        if missing:
            raise ThresholdsError(f"{seq}: baseline lacks {', '.join(missing)}")
        ok = b.get("per_run_ok") or []
        if not ok or not all(ok):
            raise ThresholdsError(f"{seq}: baseline has a failed run "
                                  f"({sum(not x for x in ok)} of {len(ok)}); re-run it first")
        if seq not in old_seqs or "skip_s" not in old_seqs[seq]:
            raise ThresholdsError(f"{seq}: no skip_s in the existing thresholds file")
        for f in ("per_run_ate_rmse", "per_run_rpe_rmse", "per_run_coverage", "per_run_n"):
            if not b.get(f) or any(x is None for x in b[f]):
                raise ThresholdsError(f"{seq}: {f} missing or incomplete")
        entry = {**{k: b[k] for k in KEY_FIELDS},
                 "ate_rmse": float(np.median(b["per_run_ate_rmse"])),
                 "rpe_rmse": float(np.median(b["per_run_rpe_rmse"])),
                 "coverage": float(min(b["per_run_coverage"])),
                 "n": int(min(b["per_run_n"])),
                 "runs": len(ok)}
        if trajectories is not None:
            from .score import find_runs
            runs = find_runs(Path(trajectories) / seq)
            if len(runs) != len(ok):
                raise ThresholdsError(f"{seq}: {len(runs)} trajectories for {len(ok)} baseline runs")
            src = runs[_representative_index(b["per_run_ate_rmse"])][1]
            rel = Path("baselines") / f"{seq}.tum"
            dst = Path(out_root or ".") / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dst)
            entry["trajectory"] = rel.as_posix()
        seqs[seq] = {"skip_s": old_seqs[seq]["skip_s"], "baselines": [entry]}
    return {"version": 2, "defaults": {"align": align}, "margins": m, "sequences": seqs}


HEADER = """\
# Gate thresholds, format v2 (session S4). GENERATED by scripts/make_thresholds.py;
# review the diff and commit it. Never loosen a margin to make CI green without a commit
# message that says why. Semantics (src/vioreg/gate.py, docs/gate.md):
#  - a result is compared only with the baseline entry whose (vio_commit, image_digest,
#    config_hash) matches; no matching entry = FAIL "needs re-baseline"
#  - hard fail: ok=false, any failed run, coverage < baseline - coverage_drop_max,
#    ate.n < baseline n, missing results when HARNESS_REQUIRE_RESULTS=1
#  - RPE: per sequence, rpe.rmse / baseline rpe_rmse <= rpe_ratio_max
#  - ATE: geometric mean over ALL sequences of ate.rmse / baseline ate_rmse
#    <= ate_geomean_ratio_max (no single-sequence ATE limit)
#  - same key but different poses than baselines/<seq>.tum = WARNING, not a failure
"""


def write(cfg: dict, path: Path, provenance_note: str) -> None:
    body = yaml.safe_dump(cfg, sort_keys=False, default_flow_style=False, width=100)
    Path(path).write_text(HEADER + f"# {provenance_note} ({date.today().isoformat()})\n" + body)


def main(argv=None) -> int:
    import argparse
    import json

    ap = argparse.ArgumentParser(description="Write configs/thresholds.yaml (v2).")
    ap.add_argument("--baseline", type=Path, default=Path("docs/variance/baseline.json"))
    ap.add_argument("--thresholds", type=Path, default=Path("configs/thresholds.yaml"),
                    help="existing file (skip_s/align are read from it) and the output")
    ap.add_argument("--rpe-ratio-max", type=float, required=True)
    ap.add_argument("--ate-geomean-ratio-max", type=float, required=True)
    ap.add_argument("--coverage-drop-max", type=float, default=0.01)
    ap.add_argument("--trajectories", type=Path, default=None,
                    help="results dir of the baseline runs; copies baselines/<seq>.tum")
    ap.add_argument("--note", default="margins from docs/gate.md")
    a = ap.parse_args(argv)
    old = yaml.safe_load(a.thresholds.read_text())
    cfg = build(json.loads(a.baseline.read_text()),
                {"rpe_ratio_max": a.rpe_ratio_max, "ate_geomean_ratio_max": a.ate_geomean_ratio_max,
                 "coverage_drop_max": a.coverage_drop_max},
                old, trajectories=a.trajectories, out_root=Path("."))
    write(cfg, a.thresholds, provenance_note=f"baseline {a.baseline}; {a.note}")
    print(a.thresholds.read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
